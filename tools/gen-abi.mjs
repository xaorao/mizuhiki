// Writes packages/chain/src/abi.ts (ABIs, shipped to browsers) and
// packages/chain/src/bytecode.ts (deploy scripts only) from the Foundry build output.
import { readFileSync, writeFileSync } from "node:fs";
const names = ["MizuhikiRegistry", "CapsuleVault", "AnchorBook"];
const head = "// Generated by tools/gen-abi.mjs from contracts/out. Do not edit.\n";
let abi = head,
  code = head;
for (const n of names) {
  const art = JSON.parse(readFileSync(`contracts/out/${n}.sol/${n}.json`, "utf8"));
  const id = n[0].toLowerCase() + n.slice(1);
  abi += `export const ${id}Abi = ${JSON.stringify(art.abi)} as const;\n`;
  code += `export const ${id}Bytecode = ${JSON.stringify(art.bytecode.object)} as const;\n`;
}
writeFileSync("packages/chain/src/abi.ts", abi);
writeFileSync("packages/chain/src/bytecode.ts", code);
console.log("wrote abi.ts and bytecode.ts");
